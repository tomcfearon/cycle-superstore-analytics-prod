CREATE
-- OR ALTER
VIEW [marts].[vw_dim_product]
AS
    SELECT
        p.product_key,
        p.stock_code,
        p.brand,
        p.erp_brand,
        p.title,
        p.product_group_title,
        -- category/subcategory casing: avoid scalar UDF per-row (performance); keep source casing
        dbo.fn_TitleCase(p.category)      AS category,
        dbo.fn_TitleCase(p.subcategory)   AS subcategory,
        CAST(p.retail_price          AS decimal(18, 2)) AS retail_price,
        CAST(p.cost_price            AS decimal(18, 2)) AS cost_price,
        CAST(p.average_cost_price    AS decimal(18, 2)) AS average_cost_price,
        CAST(p.selling_price_1       AS decimal(18, 2)) AS selling_price_1,
        CAST(p.selling_price_2       AS decimal(18, 2)) AS selling_price_2,
        CAST(p.selling_price_3       AS decimal(18, 2)) AS selling_price_3,
        CAST(p.selling_price_4       AS decimal(18, 2)) AS selling_price_4,
        CAST(p.selling_price_5       AS decimal(18, 2)) AS selling_price_5,
        CAST(p.selling_price_6       AS decimal(18, 2)) AS selling_price_6,
        CAST(p.selling_price_7       AS decimal(18, 2)) AS selling_price_7,
        CAST(p.sale_price            AS decimal(18, 2)) AS sale_price,
        CAST(p.trade_sale_price      AS decimal(18, 2)) AS trade_sale_price,
        CAST(p.is_active             AS bit) AS is_active,
        CAST(p.is_on_web             AS bit) AS is_on_web,
        CAST(p.is_discontinued       AS bit) AS is_discontinued,
        CAST(p.web_is_active         AS bit) AS web_is_active,
        CAST(p.web_is_list_hidden    AS bit) AS web_is_list_hidden,
        p.color,
        p.[size],
        p.product_options_last_refreshed,
        p.item_groupings_last_refreshed,
        p.store_db_title,
        p.web_link,
        p.main_image_link,
        p.additional_image_links,
        p.web_category_path,
        p.google_category,
        p.html_details,
        p.[gender],
        p.item_material,
        -- Keep the reporting key as text so alphanumeric product IDs are preserved.
        CAST(p.web_product_id          AS varchar(52))    AS product_id,
        TRY_CAST(p.web_parent_product_id AS int)          AS product_group_id,
        TRY_CAST(p.web_price           AS decimal(18, 2)) AS web_price,
        TRY_CAST(p.web_list_price      AS decimal(18, 2)) AS web_list_price,
        ISNULL(CAST(p.extended_warehouse_quantity AS int), 0) AS extended_warehouse_quantity,
        CAST(p.web_is_bike_product     AS bit) AS web_is_bike_product,
        p.model_year,
        p.is_new,
        -- Classification columns
        p.stock_type,
        p.bike_sundry,
        p.bike_category,
        p.electric_manual_sundry,
        p.main_bike_type,
        p.category_type,
        dbo.fn_TitleCase(p.subcategory_type) AS subcategory_type,
        p.variant_descriptor,
        CAST(p.is_distribution AS bit) AS is_distribution,
        p.main_sundry_repairs,
        -- Google Merchant Center pricing signals
        p.benchmark_price,
        p.suggested_price,
        p.clean_product_name,
        ISNULL(p.row_modified_datetime, '1900-01-01') AS row_modified_datetime -- NULL would never clear the loader's incremental watermark filter
    FROM [int].[consolidated_product] AS p
