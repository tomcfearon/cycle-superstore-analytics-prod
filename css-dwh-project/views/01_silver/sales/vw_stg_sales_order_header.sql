CREATE
-- OR ALTER
VIEW [stg].[sales_order_header] AS
SELECT
    so.TransType AS trans_type,
    so.InvoiceNo AS order_number,
    so.OpenInvoice AS open_invoice,
    so.InvoiceDate AS order_datetime,
    CAST(so.InvoiceDate AS DATE) AS order_date,
    so.Salesperson AS salesperson_name,
    so.Source AS source,
    so.CustomerCode AS customer_code,
    so.TotalValue AS total_value,
    so.DepositValue AS deposit_value,
    so.PaymentToDate AS payment_to_date,
    so.TaxRate1 AS tax_rate_1,
    so.GoodsValue1 AS goods_value_1,
    so.TaxValue1 AS tax_value_1,
    so.TaxRate2 AS tax_rate_2,
    so.GoodsValue2 AS goods_value_2,
    so.TaxValue2 AS tax_value_2,
    so.TaxRate3 AS tax_rate_3,
    so.GoodsValue3 AS goods_value_3,
    so.TaxValue3 AS tax_value_3,
    so.TaxRate4 AS tax_rate_4,
    so.GoodsValue4 AS goods_value_4,
    so.TaxValue4 AS tax_value_4,
    so.TaxRate5 AS tax_rate_5,
    so.GoodsValue5 AS goods_value_5,
    so.TaxValue5 AS tax_value_5,
    so.DeliveryAddress1 AS delivery_address_1,
    so.DeliveryAddress2 AS delivery_address_2,
    so.DeliveryTown AS delivery_town,
    so.DeliveryCounty AS delivery_county,
    so.DeliveryPostcode AS delivery_postcode,
    so.DeliveryCountry AS delivery_country,
    so.DeliveryName AS delivery_name,
    so.DeliveryCompany AS delivery_company,
    so.SiteNo AS site_no,
    NULLIF(TRIM(so.InStoreMemo), '') AS internal_note,
    so.InStoreMemo AS in_store_memo,
    so.OrderStatus AS order_status,
    so.PoNo AS po_no,
    so.PoValue AS po_value,
    so.InvCustCode AS inv_cust_code,
    CAST(so.CollectionDate AS DATE) AS collection_date,
    so.DispatchDetails AS dispatch_details,
    so.BoxNo AS box_number,
    so.PCName AS pc_name,
    so.DeliveryPhoneNo AS delivery_phone_no,
    so.DeliveryEMailAddress AS delivery_email_address,
    so.WebOrderID AS web_order_id,
    ISNULL(so.Confirmed, 0) AS is_confirmed,
    so.Confirmed AS confirmed,
    so.BikeLocation AS bike_location
FROM
    raw_ccdata.SaleOrderHeader AS so
WHERE
    so.InvoiceNo IS NOT NULL;
