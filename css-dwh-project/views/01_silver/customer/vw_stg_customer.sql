VIEW [stg].[customers] AS
SELECT
    CustomerCode AS customer_code,
    LastName AS last_name,
    Address1 AS address_1,
    Address2 AS address_2,
    Town AS town,
    County AS county,
    PostCode AS post_code,
    CustomerType AS customer_type,
    PriceBand AS price_band,
    Notes AS notes,
    MailShotFlag AS is_mail_shot,
    OnStop AS is_on_stop,
    Reason AS reason,
    AccountOpenedDate AS account_opened_date,
    AccountBalance AS account_balance,
    CreditBalance AS credit_balance,
    TurnOverToDate AS turnover_to_date,
    EMailAddress AS email_address,
    InvCustCode AS inv_cust_code,
    NextActionText AS next_action_text,
    CompanyName AS company_name,
    FirstName AS first_name,
    Country AS country,
    OrigSalesperson AS original_salesperson,
    SiteNo AS site_no,
    Sex AS gender,
    VATRegNo AS vat_reg_no,
    EmpRefNo AS emp_ref_no,
    CreditTerms AS credit_terms,
    CreditLimit AS credit_limit,
    TypeOfRiding AS type_of_riding,
    TaxLevel AS tax_level,
    Refer AS refer,
    SMSCommunication AS is_sms_communication,
    LastInStoreDate AS last_in_store_date,
    Archived AS is_archived,
    Comments AS comments,
    c.LocationID AS location_id,
    c.row_modified_datetime -- ERP-stamped datetime used for incremental source loading
FROM
    [raw_ccdata].[Customer] AS c
