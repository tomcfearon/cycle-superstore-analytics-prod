CREATE VIEW --OR ALTER 
--special products added
[int].[product_source_special_keys]
AS
SELECT v.product_key,
       v.stock_code,
       CAST (NULL AS VARCHAR (52)) AS web_product_id,
       CAST (NULL AS VARCHAR (20)) AS web_parent_product_id,
       CAST ('-' AS NVARCHAR (255)) AS raw_brand,
       'Misc' AS brand,
       v.stock_code AS title,
       'Miscellaneous' AS category,
       CAST (NULL AS VARCHAR (100)) AS subcategory,
       CAST (NULL AS DECIMAL (19, 2)) AS retail_price,
       CAST (NULL AS DECIMAL (19, 2)) AS cost_price,
       CAST (NULL AS DECIMAL (19, 2)) AS average_cost_price,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_1,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_2,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_3,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_4,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_5,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_6,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_7,
       CAST (NULL AS DECIMAL (19, 2)) AS sale_price,
       CAST (NULL AS DECIMAL (19, 2)) AS trade_sale_price,
       CAST (0 AS BIT) AS is_active,
       CAST (0 AS BIT) AS is_on_web,
       CAST (0 AS BIT) AS is_discontinued,
       CAST (NULL AS VARCHAR (30)) AS web_price,
       CAST (NULL AS VARCHAR (30)) AS web_list_price,
       CAST (NULL AS VARCHAR (20)) AS extended_warehouse_quantity,
       CAST (0 AS BIT) AS web_is_active,
       CAST (0 AS BIT) AS web_is_list_hidden,
       CAST (NULL AS NVARCHAR (100)) AS size,
       CAST (NULL AS NVARCHAR (100)) AS color,
       CAST (NULL AS DATETIME2 (0)) AS product_options_last_refreshed,
       CAST (NULL AS DATETIME2 (0)) AS item_groupings_last_refreshed,
       CAST (NULL AS NVARCHAR (255)) AS brand_name,
       CAST (NULL AS NVARCHAR (MAX)) AS web_link,
       CAST (NULL AS NVARCHAR (MAX)) AS main_image_link,
       CAST (NULL AS NVARCHAR (MAX)) AS additional_image_links,
       CAST (NULL AS INT) AS web_category_id,
       CAST (NULL AS NVARCHAR (255)) AS product_type,
       CAST (NULL AS NVARCHAR (MAX)) AS gpc_path,
       CAST (NULL AS NVARCHAR (MAX)) AS web_title,
       CAST (NULL AS NVARCHAR (MAX)) AS web_item_group_title,
       CAST (NULL AS NVARCHAR (MAX)) AS variant_descriptor,
       CAST (NULL AS NVARCHAR (MAX)) AS web_html_details,
       CAST (NULL AS NVARCHAR (100)) AS web_gender,
       CAST (NULL AS NVARCHAR (255)) AS web_item_material,
       CAST (0 AS BIT) AS web_is_bike_product,
       CAST (NULL AS VARCHAR (10)) AS model_year,
       CAST (0 AS BIT) AS is_distribution,
       'Sundry' AS main_sundry_repairs,
       CAST ('2000-01-01' AS DATETIME2 (0)) AS row_modified_datetime -- no ERP source for placeholder keys
FROM   (VALUES ('MISC-3', 'MISC'), ('SWAP-3', 'SWAP'), ('DISC-3', 'DISC'), ('OrderMain-3', 'OrderMain')) AS v(product_key, stock_code)
UNION ALL
SELECT m.product_key,
       LEFT(m.product_key, LEN(m.product_key) - 2) AS stock_code,
       CAST (NULL AS VARCHAR (52)) AS web_product_id,
       CAST (NULL AS VARCHAR (20)) AS web_parent_product_id,
       CAST (NULL AS NVARCHAR (255)) AS raw_brand,
       'Unknown' AS brand,
       LEFT(m.product_key, LEN(m.product_key) - 2) AS title,
       CAST (NULL AS VARCHAR (100)) AS category,
       CAST (NULL AS VARCHAR (100)) AS subcategory,
       CAST (NULL AS DECIMAL (19, 2)) AS retail_price,
       CAST (NULL AS DECIMAL (19, 2)) AS cost_price,
       CAST (NULL AS DECIMAL (19, 2)) AS average_cost_price,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_1,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_2,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_3,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_4,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_5,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_6,
       CAST (NULL AS DECIMAL (19, 2)) AS selling_price_7,
       CAST (NULL AS DECIMAL (19, 2)) AS sale_price,
       CAST (NULL AS DECIMAL (19, 2)) AS trade_sale_price,
       CAST (0 AS BIT) AS is_active,
       CAST (0 AS BIT) AS is_on_web,
       CAST (0 AS BIT) AS is_discontinued,
       CAST (NULL AS VARCHAR (30)) AS web_price,
       CAST (NULL AS VARCHAR (30)) AS web_list_price,
       CAST (NULL AS VARCHAR (20)) AS extended_warehouse_quantity,
       CAST (0 AS BIT) AS web_is_active,
       CAST (0 AS BIT) AS web_is_list_hidden,
       CAST (NULL AS NVARCHAR (100)) AS size,
       CAST (NULL AS NVARCHAR (100)) AS color,
       CAST (NULL AS DATETIME2 (0)) AS product_options_last_refreshed,
       CAST (NULL AS DATETIME2 (0)) AS item_groupings_last_refreshed,
       CAST (NULL AS NVARCHAR (255)) AS brand_name,
       CAST (NULL AS NVARCHAR (MAX)) AS web_link,
       CAST (NULL AS NVARCHAR (MAX)) AS main_image_link,
       CAST (NULL AS NVARCHAR (MAX)) AS additional_image_links,
       CAST (NULL AS INT) AS web_category_id,
       CAST (NULL AS NVARCHAR (255)) AS product_type,
       CAST (NULL AS NVARCHAR (MAX)) AS gpc_path,
       CAST (NULL AS NVARCHAR (MAX)) AS web_title,
       CAST (NULL AS NVARCHAR (MAX)) AS web_item_group_title,
       CAST (NULL AS NVARCHAR (MAX)) AS variant_descriptor,
       CAST (NULL AS NVARCHAR (MAX)) AS web_html_details,
       CAST (NULL AS NVARCHAR (100)) AS web_gender,
       CAST (NULL AS NVARCHAR (255)) AS web_item_material,
       CAST (0 AS BIT) AS web_is_bike_product,
       CAST (NULL AS VARCHAR (10)) AS model_year,
       CAST (0 AS BIT) AS is_distribution,
       'Main' AS main_sundry_repairs,
       CAST ('2000-01-01' AS DATETIME2 (0)) AS row_modified_datetime -- no ERP source for orphaned model keys
FROM   (SELECT DISTINCT product_key
        FROM   [int].[product_code_to_product_key_mapping]
        WHERE  product_key LIKE '%-1'
               AND product_key NOT IN ('MISC-3', 'SWAP-3', 'DISC-3', 'OrderMain-3')) AS m
WHERE  NOT EXISTS (SELECT 1
                   FROM   [stg].[bike_product] AS bs
                   WHERE  bs.product_key = m.product_key);